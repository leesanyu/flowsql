#!/usr/bin/env python3
"""Canonical product version and build snapshot generator (standard library only)."""
import argparse
import json
from pathlib import Path
import re
import subprocess

NUMBER = r"(0|[1-9][0-9]*)"
VERSION_PATTERN = re.compile(rf"{NUMBER}\.{NUMBER}\.{NUMBER}(?:-(dev|alpha|beta|rc)\.{NUMBER})?")
RECORD_BEGIN = "FLOWSQL_BUILD_INFO_BEGIN"
RECORD_END = "FLOWSQL_BUILD_INFO_END"


def parse_version(value):
    match = VERSION_PATTERN.fullmatch(value)
    if not match:
        raise ValueError(f"Invalid product version: {value!r}; expected MAJOR.MINOR.PATCH[-dev/alpha/beta/rc.N]")
    major, minor, patch, stage, number = match.groups()
    numeric = f"{major}.{minor}.{patch}"
    suffix = {"dev": ".dev", "alpha": "a", "beta": "b", "rc": "rc"}
    return numeric, numeric + (suffix[stage] + number if stage else "")


def snapshot(root):
    root = Path(root).resolve()
    text = (root / "VERSION").read_text(encoding="utf-8")
    value = text[:-1] if text.endswith("\n") else text
    parse_version(value)
    info = {"version": value, "revision": None, "dirty": None}
    # Exported source under another repository must not inherit its parent's identity.
    if not (root / ".git").exists():
        return info
    try:
        def git(*args):
            return subprocess.check_output(["git", "-C", str(root), *args],
                                           stderr=subprocess.DEVNULL, timeout=120).decode().strip()
        revision = git("rev-parse", "--verify", "HEAD")
        if not re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", revision):
            return info
        info["revision"] = revision
        info["dirty"] = bool(git("status", "--porcelain", "--untracked-files=normal"))
    except (OSError, subprocess.SubprocessError):
        pass  # Unknown identity is allowed for builds, never for release validation.
    return info


def write_if_changed(path, content):
    path = Path(path)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def generate(root, output):
    info = snapshot(root)
    output = Path(output)
    raw = json.dumps(info, separators=(",", ":"))
    header = ("// Generated by tools/product_version.py; do not edit.\n#pragma once\n"
              f"#define FLOWSQL_PRODUCT_VERSION {json.dumps(info['version'])}\n"
              f"#define FLOWSQL_PRODUCT_REVISION {json.dumps(info['revision'] or '')}\n"
              f"#define FLOWSQL_PRODUCT_DIRTY {(-1 if info['dirty'] is None else int(info['dirty']))}\n"
              f"#define FLOWSQL_PRODUCT_RECORD {json.dumps(RECORD_BEGIN + raw + RECORD_END)}\n")
    write_if_changed(output / "build-info.json", json.dumps(info, indent=2) + "\n")
    write_if_changed(output / "flowsql_build_info.h", header)
    return info


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path)
    parser.add_argument("--numeric", action="store_true")
    args = parser.parse_args()
    try:
        if args.numeric:
            value = (args.root / "VERSION").read_text(encoding="utf-8").removesuffix("\n")
            print(parse_version(value)[0])
        else:
            print(json.dumps(generate(args.root, args.output) if args.output else snapshot(args.root)))
    except (OSError, ValueError) as exc:
        parser.exit(1, f"product version: {exc}\n")


if __name__ == "__main__":
    main()
